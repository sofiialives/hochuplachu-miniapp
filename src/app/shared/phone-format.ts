// formatPhoneInput — маска ввода телефона. Унифицирована между
// requisites.dialog (форма пополнения / выпуска / продления) и
// verification.page (phone-step strict-режима).
//
// Поведение:
//   - оставляет только цифры (свободный ввод, paste, разделители — всё
//     срезается);
//   - ограничивает 15 цифрами (e.164 max);
//   - если есть хотя бы одна цифра — префикс '+' добавляется автоматически,
//     чтобы пользователь не задумывался о международном формате;
//   - пустой ввод → пустая строка (плейсхолдер не перекрывается).
//
// Жёсткой национальной маски нет: coincat принимает международный формат
// (`+0*` в его FieldMaskPipe), банк/страна могут быть любыми.
export function formatPhoneInput(input: string): string {
  const digits = (input ?? '').replace(/\D+/g, '').slice(0, 15);
  return digits ? '+' + digits : '';
}
